"""Emit exact endpoint arithmetic only; no interval or analytic proof is imported."""
from fractions import Fraction
import argparse
import hashlib
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true',
                    help='check exact generated bytes without writing files')
args = parser.parse_args()

root = Path(__file__).resolve().parent.parent
source = root / 'certificates/complement_residual_enrichment_shift_search.json'
data = json.loads(source.read_text())
rows = data['shifts']
rho = Fraction(data['rho_exact'])
assert len(rows) == 231
fields = ['mu_exact', 'beta_exact', 'theta_exact', 'retained_energy_exact', 'alpha_exact']
def q(value):
    return '(' + str(Fraction(value)).replace('/', ' / ') + ')'
lines = ['''import Mathlib.Tactic.NormNum
import Mathlib.Tactic.Linarith
import Mathlib.Data.Real.Basic
import Mathlib.Data.List.Defs

set_option maxRecDepth 4096

/-! Exact rational consequences of the 231 archived endpoint records.
The interval matrix comparisons and their analytic interpretation are NOT proved here.
Generated by generate_endpoints.py; provenance is in endpoint-source.json. -/
namespace OddThetaWeil.Endpoints

structure Endpoint where
  mu : ℚ
  beta : ℚ
  theta : ℚ
  retained : ℚ
  loss : ℚ
  passes : Bool

def rho : ℚ := 979236349 / 2000000000000

def Valid (c : Endpoint) : Prop :=
  0 < c.mu ∧ 0 < c.beta ∧ rho < c.mu ∧ 0 < c.theta ∧
  c.retained = 1 - c.theta ∧
  c.loss = rho + c.theta * (c.mu - rho) ∧
  (c.passes = true ↔ c.theta < 1)

/-- Algebraic transfer from the original form bound and residual comparison. -/
theorem retained_energy_loss {a e n r ρ θ s : ℝ}
    (hform : e - ρ * n - r ≤ a)
    (hresidual : r ≤ θ * (e + s * n)) :
    (1 - θ) * e - (ρ + θ * s) * n ≤ a := by
  nlinarith

/-- An upward rounded scalar loss remains valid for a nonnegative squared norm. -/
theorem retained_energy_loss_rounded {a e n r ρ θ μ α : ℝ}
    (hn : 0 ≤ n) (hform : e - ρ * n - r ≤ a)
    (hresidual : r ≤ θ * (e + (μ - ρ) * n))
    (hloss : ρ + θ * (μ - ρ) ≤ α) :
    (1 - θ) * e - α * n ≤ a := by
  have h := retained_energy_loss hform hresidual
  have hmul := mul_le_mul_of_nonneg_right hloss hn
  linarith
''']
mapping=[]
for i,row in enumerate(rows):
    mu,beta,theta,retained,loss = (Fraction(row[f]) for f in fields)
    assert mu > rho > 0 and beta > 0 and theta > 0
    assert retained == 1-theta and loss == rho+theta*(mu-rho)
    assert row['passes'] == (theta < 1)
    name=f'endpoint_{i:03d}'
    vals=', '.join(q(row[f]) for f in fields)+', '+str(row['passes']).lower()
    lines.append(f'def {name} : Endpoint := ⟨{vals}⟩\n\ntheorem {name}_checked : Valid {name} := by\n  norm_num [Valid, {name}, rho]\n')
    mapping.append({'index':i,'json_pointer':f'/shifts/{i}','definition':f'OddThetaWeil.Endpoints.{name}','theorem':f'OddThetaWeil.Endpoints.{name}_checked','exact':{f:row[f] for f in fields},'passes':row['passes']})
lines.append('def endpoints : List Endpoint := [\n  '+',\n  '.join(f'endpoint_{i:03d}' for i in range(len(rows)))+'\n]\n')
lines.append('theorem endpoint_count : endpoints.length = 231 := by rfl\n')
# List.Forall constructors retain a direct proof for each source row.
proof=f'endpoint_{len(rows)-1:03d}_checked'
for i in reversed(range(len(rows)-1)): proof=f'And.intro endpoint_{i:03d}_checked ({proof})'
lines.append('theorem all_endpoints_checked : List.Forall Valid endpoints := by\n  exact '+proof+'\n')
selected=[(59,'paper_first','17381/500000'),(210,'paper_second','19741/500000'),(221,'paper_third',rows[221]['alpha_exact'])]
for i,name,upper in selected:
    row=rows[i]; theta=q(row['theta_exact']); mu=q(row['mu_exact']); retained=q(row['retained_energy_exact']); upperq=q(upper)
    lines.append(f'''/-- Conditional real form consequence for source row {i}; analytic premises remain explicit. -/
theorem {name} {{a e n r : ℝ}} (hn : 0 ≤ n)
    (hform : e - (979236349 / 2000000000000) * n - r ≤ a)
    (hresidual : r ≤ {theta} * (e + ({mu} - 979236349 / 2000000000000) * n)) :
    {retained} * e - {upperq} * n ≤ a := by
  have h := retained_energy_loss_rounded hn hform hresidual
    (α := {upperq}) (by norm_num)
  norm_num at h ⊢
  exact h
''')
lines.append('end OddThetaWeil.Endpoints\n')
manifest={'source':'certificates/complement_residual_enrichment_shift_search.json','source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'rho_json_pointer':'/rho_exact','rho_exact':data['rho_exact'],'record_count':len(rows),'scope':'Exact rational arithmetic and conditional real lower-bound transfer only. No verification of interval balls, matrices, spectral inequalities, or continuum analytic premises.','fields':{'mu':'mu_exact','beta':'beta_exact','theta':'theta_exact','retained':'retained_energy_exact','loss':'alpha_exact','passes':'passes'},'records':mapping,'paper_selected':[{'index':i,'theorem':f'OddThetaWeil.Endpoints.{name}','loss_upper_exact':str(Fraction(upper))} for i,name,upper in selected]}
outputs = {
    root / 'lean/OddThetaWeil/Endpoints.lean': '\n'.join(lines).encode('utf-8'),
    root / 'lean/endpoint-source.json': (json.dumps(manifest, indent=2) + '\n').encode('utf-8'),
}
if args.check:
    mismatches = [str(path.relative_to(root)) for path, expected in outputs.items()
                  if not path.is_file() or path.read_bytes() != expected]
    if mismatches:
        parser.exit(1, 'Generated files differ or are missing: ' + ', '.join(mismatches) + '\n')
    print(f'Checked exact bytes and arithmetic for {len(rows)} records; no files written.')
else:
    for path, expected in outputs.items():
        path.write_bytes(expected)
    print(f'Generated and exact-arithmetic checked {len(rows)} records.')
